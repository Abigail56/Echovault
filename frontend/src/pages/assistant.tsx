import { Bot, FileText, Info, Scale, SendHorizontal, Settings, ShieldAlert, User } from "lucide-react";
import Head from "next/head";
import Link from "next/link";
import { type FormEvent, type KeyboardEvent, useEffect, useRef, useState } from "react";

import { appLayout } from "@/components/layout/AppShell";
import { Markdown } from "@/components/ui/Markdown";
import { PageHeader } from "@/components/ui/PageHeader";
import { ProjectSelect } from "@/components/ui/ProjectSelect";
import { ErrorState, FullPageSpinner } from "@/components/ui/States";
import { useAsync } from "@/hooks/useAsync";
import { errorMessage } from "@/lib/api/client";
import { assistantApi } from "@/lib/api/services";
import type { AssistantAnswer } from "@/lib/api/types";
import type { PageWithLayout } from "@/lib/layout";

type Turn =
  | { id: number; role: "user"; text: string }
  | { id: number; role: "assistant"; answer: AssistantAnswer }
  | { id: number; role: "error"; text: string };

const SUGGESTIONS = [
  "What have I written about this project's architecture?",
  "Summarise my notes on deployment.",
  "Which decisions mention the database?",
];

function AnswerView({ answer }: { answer: AssistantAnswer }) {
  const cited = answer.sources.filter((s) => s.cited);
  const other = answer.sources.filter((s) => !s.cited);
  return (
    <div className="min-w-0 flex-1">
      {!answer.grounded && (
        <p className="text-meta mb-1 flex items-center gap-1">
          <Info className="size-3.5" aria-hidden /> System message (no AI provider was called)
        </p>
      )}
      <Markdown>{answer.answer}</Markdown>
      {answer.sources.length > 0 && (
        <div className="mt-4">
          <h3 className="text-meta mb-2 font-medium tracking-wide uppercase">Sources from your notes and decisions</h3>
          <ol className="grid gap-2">
            {[...cited, ...other].map((s) => (
              <li key={s.id}>
                <Link
                  href={s.type === "decision" ? `/decisions/${s.id}` : `/vault/${s.id}`}
                  className={`hover:border-primary/40 flex gap-3 rounded-field border p-3 transition-colors ${s.cited ? "border-base-300 bg-base-100" : "border-base-300/60 bg-base-100/60 opacity-80"}`}
                >
                  <span className="badge badge-sm badge-primary badge-soft shrink-0">[{s.ref}]</span>
                  <span className="min-w-0">
                    <span className="flex items-center gap-1.5 text-sm font-medium">
                      {s.type === "decision" ? <Scale className="size-3.5 shrink-0" aria-hidden /> : <FileText className="size-3.5 shrink-0" aria-hidden />}
                      <span className="sr-only">{s.type === "decision" ? "Decision:" : "Note:"}</span>
                      <span className="truncate">{s.title}</span>
                    </span>
                    {s.excerpt && <span className="text-muted line-clamp-2 block text-xs">{s.excerpt}</span>}
                    {!s.cited && <span className="text-meta block">Retrieved but not cited in the answer</span>}
                  </span>
                </Link>
              </li>
            ))}
          </ol>
        </div>
      )}
      {answer.model && <p className="text-meta mt-3">Generated by {answer.model}. AI answers can be wrong; check the sources.</p>}
    </div>
  );
}

const AssistantPage: PageWithLayout = () => {
  const status = useAsync(() => assistantApi.status(), []);
  const [turns, setTurns] = useState<Turn[]>([]);
  const [question, setQuestion] = useState("");
  const [projectId, setProjectId] = useState<string | null>(null);
  const [pending, setPending] = useState(false);
  const endRef = useRef<HTMLDivElement>(null);
  const nextId = useRef(1);

  useEffect(() => {
    endRef.current?.scrollIntoView({ behavior: "smooth", block: "end" });
  }, [turns, pending]);

  const ask = async (text: string) => {
    const q = text.trim();
    if (q.length < 3 || pending) return;
    setQuestion("");
    setTurns((t) => [...t, { id: nextId.current++, role: "user", text: q }]);
    setPending(true);
    try {
      const answer = await assistantApi.ask(q, projectId);
      setTurns((t) => [...t, { id: nextId.current++, role: "assistant", answer }]);
    } catch (error) {
      setTurns((t) => [...t, { id: nextId.current++, role: "error", text: errorMessage(error) }]);
    } finally {
      setPending(false);
    }
  };

  const onSubmit = (event: FormEvent) => {
    event.preventDefault();
    void ask(question);
  };
  const onKeyDown = (event: KeyboardEvent<HTMLTextAreaElement>) => {
    if (event.key === "Enter" && !event.shiftKey) {
      event.preventDefault();
      void ask(question);
    }
  };

  const head = (
    <Head>
      <title>Assistant · EchoVault Nexus</title>
    </Head>
  );

  if (status.loading) return <FullPageSpinner />;
  if (status.error) return <ErrorState error={status.error} onRetry={status.reload} />;

  if (!status.data?.configured) {
    return (
      <>
        {head}
        <PageHeader title="Assistant" description="Ask questions and get answers grounded in your own notes." />
        <div className="surface max-w-2xl p-6">
          <div className="flex items-start gap-3">
            <Settings className="text-warning mt-0.5 size-5 shrink-0" aria-hidden />
            <div className="min-w-0 space-y-2 text-sm">
              <h2 className="text-section">The assistant isn&apos;t set up yet</h2>
              <p className="text-muted">
                No AI provider is configured on the server, so no questions can be answered. Nothing is simulated: once a provider is
                configured, answers are generated from your saved knowledge with links to the notes they came from.
              </p>
              <p className="text-muted">To enable it, set these in <code>backend/.env</code> and restart the backend:</p>
              <pre className="bg-sunken overflow-x-auto rounded-box p-3 text-xs">{`# Claude (paid API key)
AI_PROVIDER=anthropic
AI_API_KEY=sk-ant-...

# or a free local model via Ollama
AI_PROVIDER=openai_compatible
AI_BASE_URL=http://127.0.0.1:11434/v1
AI_MODEL=llama3.1`}</pre>
              <p className="text-muted">
                Meanwhile, <Link href="/search" className="link link-primary">keyword search</Link> works without any provider.
              </p>
            </div>
          </div>
        </div>
      </>
    );
  }

  return (
    <>
      {head}
      <PageHeader
        title="Assistant"
        description="Answers come from your own notes, with links to every source used."
        actions={
          <div className="w-56">
            <ProjectSelect value={projectId} onChange={setProjectId} aria-label="Limit to a project" emptyLabel="All knowledge" />
          </div>
        }
      />

      <div className="alert alert-soft alert-info mb-4 text-xs">
        <ShieldAlert className="size-4" aria-hidden />
        <span>
          When you ask a question, your most relevant notes and decisions (archived notes excluded) are sent to {status.data.provider === "anthropic" ? "Anthropic" : "the configured AI provider"} ({status.data.model})
          to generate the answer. Only your own notes are ever included.
        </span>
      </div>

      <div className="surface flex min-h-[55vh] flex-col">
        <div className="flex-1 space-y-6 p-4 sm:p-6" aria-live="polite">
          {turns.length === 0 && (
            <div className="flex flex-col items-center py-10 text-center">
              <Bot className="text-primary mb-3 size-8" aria-hidden />
              <h2 className="text-section">Ask about anything you&apos;ve saved</h2>
              <p className="text-muted mt-1 max-w-md text-sm">
                The assistant searches your vault for matching notes and answers only from them. If nothing relevant is found, it says so.
              </p>
              <div className="mt-5 flex flex-wrap justify-center gap-2">
                {SUGGESTIONS.map((s) => (
                  <button key={s} type="button" className="btn btn-sm btn-ghost border-base-300 border font-normal" onClick={() => ask(s)}>
                    {s}
                  </button>
                ))}
              </div>
            </div>
          )}
          {turns.map((turn) =>
            turn.role === "user" ? (
              <div key={turn.id} className="flex justify-end gap-3">
                <p className="bg-primary text-primary-content max-w-[85%] rounded-box rounded-tr-sm px-4 py-2.5 text-sm break-words whitespace-pre-line">{turn.text}</p>
                <span className="bg-base-200 grid size-8 shrink-0 place-items-center rounded-full" aria-hidden>
                  <User className="size-4" />
                </span>
              </div>
            ) : turn.role === "assistant" ? (
              <div key={turn.id} className="flex gap-3">
                <span className="bg-primary/10 text-primary grid size-8 shrink-0 place-items-center rounded-full" aria-hidden>
                  <Bot className="size-4" />
                </span>
                <AnswerView answer={turn.answer} />
              </div>
            ) : (
              <div key={turn.id} role="alert" className="alert alert-error alert-soft text-sm">
                {turn.text}
              </div>
            ),
          )}
          {pending && (
            <div className="flex items-center gap-3" role="status">
              <span className="bg-primary/10 text-primary grid size-8 shrink-0 place-items-center rounded-full" aria-hidden>
                <Bot className="size-4" />
              </span>
              <span className="text-muted flex items-center gap-2 text-sm">
                <span className="loading loading-dots loading-sm" aria-hidden /> Searching your notes and writing an answer…
              </span>
            </div>
          )}
          <div ref={endRef} />
        </div>
        <form onSubmit={onSubmit} className="border-base-300 flex items-end gap-2 border-t p-3 sm:p-4">
          <label htmlFor="assistant-question" className="sr-only">
            Your question
          </label>
          <textarea
            id="assistant-question"
            className="textarea min-h-12 flex-1 resize-none"
            rows={1}
            maxLength={2000}
            placeholder="Ask a question about your notes…"
            value={question}
            onChange={(e) => setQuestion(e.target.value)}
            onKeyDown={onKeyDown}
          />
          <button type="submit" className="btn btn-primary btn-square h-12 w-12" disabled={pending || question.trim().length < 3} aria-label="Send question">
            <SendHorizontal className="size-5" aria-hidden />
          </button>
        </form>
      </div>
      <p className="text-meta mt-2">Each question is answered independently; conversations are not saved.</p>
    </>
  );
};

AssistantPage.getLayout = appLayout;
export default AssistantPage;
